/**
 * Deterministic PRNG (mulberry32). Decorative randomness must be identical on the server and in the
 * browser, otherwise hydration fails; `Math.random()` during render can never guarantee that.
 */
export function seededRandom(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
